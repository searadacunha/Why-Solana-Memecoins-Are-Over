#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Ticket reconciliation, written to ticket_reconciliation_phase3.md.

For every collected window, the SOL of each creation-slot curve buyer three ways:
  old       the first parser: a transaction's curve SOL split pro rata of the
            tokens each wallet received (wrong when one transaction buys for
            several wallets, since the price climbs inside the transaction);
  new       the SOL each wallet itself sent to the curve (System transfers,
            code/09_bundle_snipe.buyers_of_tx, now fparse.leg_sol), the
            creator's own first buy in the creation transaction included;
  detector  the tickets the detector logged from the program's TradeEvents.
Then what the correction changes: the core set (5 SOL rule) and the bundle
features built on the tickets.
"""
from __future__ import annotations

import gzip
import json
import os
import statistics

import feat_30_build as FB
import fparse


def main() -> None:
    alerts = {r["mint"]: r for r in FB.pde.load_journal() if r["genre"] == "alerte_lancement"}
    n_win = n_multi_tx = n_alert_multi = 0
    abs_diff_old, abs_diff_new, rel_old = [], [], []
    core_changed = 0
    feat_old: dict[str, list[float]] = {"cv": [], "gini": [], "top1": [], "min": []}
    feat_new: dict[str, list[float]] = {"cv": [], "gini": [], "top1": [], "min": []}
    unmatched = 0
    mism: list[tuple[str, list[float], list[float], bool]] = []
    for f in sorted(os.listdir(FB.WIN)):
        if not f.endswith(".json.gz"):
            continue
        w = json.load(gzip.open(os.path.join(FB.WIN, f), "rt"))
        a = alerts[w["mint"]]
        recs, _ = fparse.parse_window(w)
        slot0 = recs[0]["slot"]
        old: dict[str, float] = {}
        new: dict[str, float] = {}
        vers: dict[str, set[str]] = {}
        multi = 0
        for r in recs:
            if r["slot"] == slot0 and r.get("kind") == "create":
                # the creator's own first buy (fparse.curve_transfers), a ticket for the detector
                for o, v in (r.get("leg_sol") or {}).items():
                    new[o] = new.get(o, 0.0) + v
                continue
            if r["slot"] != slot0 or r.get("kind") != "buy" or r.get("venue") != "curve":
                continue
            legs = {o: v for o, v in (r.get("legs") or {}).items() if v > 0}
            tot = sum(legs.values())
            if len(legs) > 1:
                multi += 1
            for o, v in legs.items():
                old[o] = old.get(o, 0.0) + abs(r["v_sol"]) * v / tot
            for o, v in (r.get("leg_sol") or {}).items():
                new[o] = new.get(o, 0.0) + v
                vers.setdefault(o, set()).add(str(w["txs"][r["sig"]].get("version")))
        n_win += 1
        n_multi_tx += multi
        n_alert_multi += multi > 0
        co = {o for o, v in old.items() if v >= 5}
        cn = {o for o, v in new.items() if v >= 5}
        core_changed += co != {o for o in cn if o != next((r["signer"] for r in recs if r.get("kind") == "create"),
                                                              None)}
        bot = sorted(a.get("tickets") or a["bloc"].get("tickets") or [])
        tn = sorted(new[o] for o in cn)
        to = sorted(old[o] for o in co)
        if bot and len(tn) == len(bot):
            abs_diff_new += [abs(x - y) for x, y in zip(tn, bot)]
        elif bot:
            unmatched += 1
            # the detector reads the slot with maxSupportedTransactionVersion 0: a buyer whose
            # only creation-slot buys are version-1 transactions is invisible to it
            seen = sorted(new[o] for o in cn if vers.get(o, {"0"}) != {"1"})
            v1 = len(seen) == len(bot) and all(abs(x - y) < 0.01 for x, y in zip(seen, bot))
            mism.append((w["mint"], bot, tn, v1))
        if bot and len(to) == len(bot):
            abs_diff_old += [abs(x - y) for x, y in zip(to, bot)]
            rel_old += [abs(x - y) / y for x, y in zip(to, bot)]
        for tk, store in ((to, feat_old), (tn, feat_new)):
            if len(tk) > 1:
                s = sum(tk)
                store["cv"].append(statistics.pstdev(tk) / (s / len(tk)))
                store["gini"].append(FB.gini(tk))
                store["top1"].append(max(tk) / s)
                store["min"].append(min(tk))

    def q(v: list[float], p: float) -> float:
        v = sorted(v)
        return v[int(p * (len(v) - 1))] if v else float("nan")
    lines = ["# Ticket reconciliation (phase 3)", "",
             "Generated by `code/qa_20_tickets.py` on %d collected windows." % n_win, "",
             "| quantity | value |", "|---|---:|",
             "| creation-slot curve transactions buying for several wallets | %d |" % n_multi_tx,
             "| alerts with at least one such transaction | %d |" % n_alert_multi,
             "| core tickets compared with the detector (old) | %d |" % len(abs_diff_old),
             "| old calculation: absolute gap to the detector, median / q90 / max (SOL) | %.4f / %.4f / %.3f |" % (
                 q(abs_diff_old, .5), q(abs_diff_old, .9), max(abs_diff_old or [0])),
             "| old calculation: relative gap, median / q90 / max | %.2f %% / %.2f %% / %.1f %% |" % (
                 100 * q(rel_old, .5), 100 * q(rel_old, .9), 100 * max(rel_old or [0])),
             "| new calculation: absolute gap to the detector, median / q90 / max (SOL) | %.4f / %.4f / %.4f |" % (
                 q(abs_diff_new, .5), q(abs_diff_new, .9), max(abs_diff_new or [0])),
             "| alerts whose core count differs from the detector's (new) | %d |" % unmatched,
             "| of which: the detector's tickets are ours without the version-1-only buyers | %d |" % sum(
                 1 for x in mism if x[3]),
             "| alerts whose core set (5 SOL rule) changes with the correction | %d |" % core_changed, "",
             "## Impact on the ticket features (median over alerts, old -> new)", "",
             "| feature | old | new |", "|---|---:|---:|"]
    for k, nm in (("cv", "b_ticket_cv"), ("gini", "b_gini"), ("top1", "b_top1"), ("min", "b_ticket_min")):
        lines.append("| %s | %.4f | %.4f |" % (nm, q(feat_old[k], .5), q(feat_new[k], .5)))
    lines += ["", "## Alerts whose core count differs from the detector's", "",
              "| mint | detector tickets (SOL) | new core tickets (SOL) | explained by version-1 buys |",
              "|---|---|---|---|"]
    for m, b, t, v1 in mism:
        lines.append("| %s | %s | %s | %s |" % (m, ", ".join("%.3f" % x for x in b), ", ".join("%.3f" % x for x in t),
                                              "yes" if v1 else "NO"))
    lines += ["", "The new calculation is the one every feature now uses (fparse.leg_sol). The detector's tickets "
              "come from the program's TradeEvents; the System transfers to the curve reproduce them.",
              "", "Second correction (2026-09-29): the creation transaction. The curve's token balance rises there "
              "(the supply lands on it), so the first parser never read it as a buy, and the creator's own first "
              "buy was missing from the tickets; when it is 5 SOL or more the detector counts it as a ticket. It is "
              "now read from the creator's System transfer to the curve (fparse.curve_transfers, without the rent "
              "that creates the curve account), and counted in the bundle tickets when it reaches 5 SOL; the "
              "creator keeps its own role for the wallet features. `b_creator_buy_sol` read a field the parser "
              "never wrote and was 0 everywhere; it now reads the same transfer.",
              "", "Version-1 transactions (on mainnet from mid-September 2026). The detector fetches the creation "
              "slot with maxSupportedTransactionVersion 0 and silently drops the version-1 transactions, so a "
              "sniper who bought only through one is missing from its tickets. The collectors of this study ask "
              "for version 1, so the bundle features count that sniper: they describe the chain, not the "
              "detector's view of it. The alert population itself is what the detector raised, with that blind "
              "spot."]
    with open(os.path.join(FB.STUDY, "ticket_reconciliation_phase3.md"), "w", encoding="utf8") as fh:
        fh.write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
